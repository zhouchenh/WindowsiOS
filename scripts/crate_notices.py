"""Write the licence notices of every crate compiled into a Rust static library.

Takes the crates `cargo tree` resolves for the package on aarch64-apple-ios from its Cargo.lock
(normal dependencies only, no proc-macro crates: those run at compile time and are not in the
binary), with its default features plus --features, and copies each crate's
LICENSE/LICENCE/COPYING/NOTICE files from the cargo registry. A -sys crate also has the licence
files of the C library it bundles copied (aws-lc-sys: AWS-LC's LICENSE and
third_party/fiat/LICENSE); a path crate without its own falls back to its workspace's.

    crate_notices.py [--features F] [--check-binary LIB] <package dir> <output file> <title line>

--check-binary: LIB was built elsewhere (a prebuilt static library); fail unless every crate whose
registry source path appears in it (panic locations and the like) is one of the crates listed, so
a lockfile or feature set that does not match the binary is caught.

scripts/build_jit_deps.sh runs it for idevice's FFI inside StikJIT.framework.
"""
import argparse
import json
import re
import subprocess
from pathlib import Path

PREFIXES = ('LICENSE', 'LICENCE', 'COPYING', 'NOTICE')
SKIP_DIRS = {'test', 'tests', 'testdata', 'fuzz', 'target'}


def licence_files(folder: Path, bundled: bool) -> list[Path]:
    found = [f for f in folder.iterdir() if f.is_file() and f.name.upper().startswith(PREFIXES)]
    if bundled:
        for f in folder.rglob('*'):
            parts = {p.lower() for p in f.relative_to(folder).parts[:-1]}
            if (f.is_file() and f.parent != folder and f.name.upper().startswith(PREFIXES)
                    and not parts & SKIP_DIRS):
                found.append(f)
    return sorted(found, key=lambda f: (len(f.relative_to(folder).parts), str(f)))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--features', default='')
    parser.add_argument('--check-binary', type=Path)
    parser.add_argument('package_dir', type=Path)
    parser.add_argument('output', type=Path)
    parser.add_argument('title')
    args = parser.parse_args()
    package_dir = args.package_dir.resolve()

    features = ['--features', args.features] if args.features else []
    metadata = json.loads(subprocess.run(
        ['cargo', 'metadata', '--format-version', '1', '--locked', '--filter-platform', 'aarch64-apple-ios']
        + features, cwd=package_dir, check=True, capture_output=True, text=True).stdout)
    root = metadata['resolve']['root']
    if root is None:
        raise SystemExit(f'{package_dir} is not a package')
    packages = {(p['name'], p['version']): p for p in metadata['packages']}
    root_package = next(p for p in metadata['packages'] if p['id'] == root)

    tree = ['cargo', 'tree', '--locked', '-p', root_package['name'], '--target', 'aarch64-apple-ios',
            '-e', 'normal,no-proc-macro', '--prefix', 'none', '--format', '{p}'] + features
    lines = subprocess.run(tree, cwd=package_dir, check=True, capture_output=True, text=True).stdout
    shipped = set()
    for line in lines.splitlines():
        match = re.match(r'(\S+) v(\S+)', line.strip())
        if match and (match.group(1), match.group(2)) != (root_package['name'], root_package['version']):
            shipped.add((match.group(1), match.group(2)))

    if args.check_binary:
        strings = subprocess.run(['strings', '-a', str(args.check_binary)], check=True,
                                 capture_output=True, text=True, errors='replace').stdout
        seen = set(re.findall(r'registry/src/[^/\s]+/([A-Za-z0-9_.+-]+?)-(\d+\.\d+\.\d+[^/\s]*)/', strings))
        unlisted = sorted(f'{name} {version}' for name, version in seen - shipped)
        if unlisted:
            raise SystemExit(f'{args.check_binary} contains crates the lockfile does not give: {", ".join(unlisted)}')
        print(f'{len(seen)} crates seen in {args.check_binary.name}, all listed')

    workspace = Path(metadata['workspace_root'])
    out = [args.title, 'Generated by scripts/crate_notices.py from Cargo.lock. Each crate is listed with',
           'the licence it declares and the licence files it ships.', '']
    missing, seen = [], {}
    for key in sorted(shipped):
        package = packages[key]
        folder = Path(package['manifest_path']).parent
        files = licence_files(folder, package['name'].endswith('-sys'))
        base = folder
        if not files and package.get('source') is None and folder != workspace:
            files, base = licence_files(workspace, False), workspace
        out.append('=' * 78)
        out.append(f"{package['name']} {package['version']} ({package.get('license') or 'see files'})")
        if package.get('repository'):
            out.append(package['repository'])
        if not files:
            missing.append(package['name'])
            out.append('(no licence file in the published crate; licence as declared above)')
        for f in files:
            name = f.relative_to(base).as_posix()
            text = f.read_text(errors='replace').rstrip()
            if text in seen:
                out.append(f'--- {name}: same text as {seen[text]} above ---')
            else:
                seen[text] = f"{package['name']} {name}"
                out += ['', f'--- {name} ---', text]
        out.append('')

    args.output.write_text('\n'.join(out) + '\n')
    print(f'{len(shipped)} crates -> {args.output}' + (f" (no licence file: {', '.join(missing)})" if missing else ''))


if __name__ == '__main__':
    main()
